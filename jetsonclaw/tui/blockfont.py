def render_block(word: str) -> str:
    """Render a word in massive block letters."""
    lines = [""] * 6
    for ch in word.upper():
        glyph = BLOCK_FONT.get(ch, BLOCK_FONT[' '])
        for row in range(6):
            lines[row] += glyph[row] + " "
    return "\n".join(lines)
